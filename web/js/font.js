// Full-cell glyphs, described as a test on the dot (x 0..5, y 0..7). The
// horizontal centre line is y = 3 and the vertical one x = 2, matching the
// middle of the 5x7 glyphs so text and frames line up.
const H = (y) => y === 3;
const V = (x) => x === 2;
const FULL = {
  '█': () => true,
  '▓': (x, y) => !(x % 2 === 0 && y % 2 === 0),
  '▒': (x, y) => (x + y) % 2 === 0,
  '░': (x, y) => x % 2 === 0 && y % 2 === 0,
  '▀': (x, y) => y < 4,
  '▄': (x, y) => y >= 4,
  '▌': (x) => x < 3,
  '▐': (x) => x >= 3,
  '▬': (x, y) => y >= 2 && y <= 4,
  '─': (x, y) => H(y),
  '│': (x) => V(x),
  '┌': (x, y) => (H(y) && x >= 2) || (V(x) && y >= 3),
  '┐': (x, y) => (H(y) && x <= 2) || (V(x) && y >= 3),
  '└': (x, y) => (H(y) && x >= 2) || (V(x) && y <= 3),
  '┘': (x, y) => (H(y) && x <= 2) || (V(x) && y <= 3),
  '├': (x, y) => V(x) || (H(y) && x >= 2),
  '┤': (x, y) => V(x) || (H(y) && x <= 2),
  '┬': (x, y) => H(y) || (V(x) && y >= 3),
  '┴': (x, y) => H(y) || (V(x) && y <= 3),
  '┼': (x, y) => H(y) || V(x),
  '═': (x, y) => y === 2 || y === 4,
  '║': (x) => x === 1 || x === 3,
  '╔': (x, y) => (y === 2 && x >= 1) || (x === 1 && y >= 2) || (y === 4 && x >= 3) || (x === 3 && y >= 4),
  '╗': (x, y) => (y === 2 && x <= 3) || (x === 3 && y >= 2) || (y === 4 && x <= 1) || (x === 1 && y >= 4),
  '╚': (x, y) => (y === 4 && x >= 1) || (x === 1 && y <= 4) || (y === 2 && x >= 3) || (x === 3 && y <= 2),
  '╝': (x, y) => (y === 4 && x <= 3) || (x === 3 && y <= 4) || (y === 2 && x <= 1) || (x === 1 && y <= 2),
  '╪': (x, y) => y === 2 || y === 4 || V(x),
  '╫': (x, y) => x === 1 || x === 3 || H(y),
};

const cache = new Map();

// The glyph for `ch` as 48 booleans, row by row. Lowercase is shown as
// uppercase, accents are dropped, and anything unknown becomes a blank.
export function glyph(ch) {
  let bits = cache.get(ch);
  if (bits) return bits;
  bits = new Array(CELL_W * CELL_H).fill(false);
  if (FULL[ch]) {
    for (let y = 0; y < CELL_H; y++) {
      for (let x = 0; x < CELL_W; x++) bits[y * CELL_W + x] = FULL[ch](x, y);
    }
  } else {
    const rows = G[normalise(ch)];
    if (rows) {
      rows.split(' ').forEach((row, y) => {
        for (let x = 0; x < 5; x++) bits[y * CELL_W + x] = row[x] === '#';
      });
    }
  }
  cache.set(ch, bits);
  return bits;
}

export function normalise(ch) {
  if (G[ch] || FULL[ch]) return ch;
  const up = ch.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
  return G[up] ? up : ' ';
}

export const GLYPHS = [...Object.keys(G), ...Object.keys(FULL)];
